def test_render_quotes_and_reserved_names(tmp_path: Path) -> None:
    """A description ending in a quote, an input named ``Field`` (``field`` in snake case) and an
    action named ``Field`` must not break or silently corrupt the generated module."""
    describe = {
        "description": 'Say "hi"',
        "inputs": [
            {"name": "Field", "type": "STRING"},
            {"name": "str", "type": "STRING"},
            {"name": "leadId", "type": "ID"},
        ],
        "outputs": [{"name": "field", "type": "STRING"}],
    }
    actions = [ActionDescribe("flow", "Field", describe), ActionDescribe("flow", "Other", describe)]
    for pyd, name in ((False, "gen_reserved_dc"), (True, "gen_reserved_pd")):
        src = render_actions(actions, header="# test\n", pydantic=pyd)
        path = tmp_path / f"{name}.py"
        path.write_text(src)
        mod = _load(path, name)
        assert mod.Field2.__doc__ == 'Say "hi"'
        stub = mod.Other(field_="a", str_="b", lead_id="00Qxx0000000001AAA")
        assert (stub.field_, stub.str_, stub.lead_id) == ("a", "b", "00Qxx0000000001AAA")
        if pyd:
            assert stub.model_dump(by_alias=True) == {
                "Field": "a",
                "str": "b",
                "leadId": "00Qxx0000000001AAA",
            }


