from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "unasync.py"


@pytest.fixture(scope="module")
def unasync() -> ModuleType:
    spec = importlib.util.spec_from_file_location("esf_unasync", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_generated_sync_is_up_to_date() -> None:
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, check=False
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_main_check_in_process(unasync: ModuleType) -> None:
    assert unasync.main(["--check"]) == 0


@pytest.mark.parametrize(
    ("src", "out"),
    [
        ("class AsyncSalesforce:", "class Salesforce:"),
        ("httpx.AsyncClient(", "httpx.Client("),
        ("async def f(self):", "def f(self):"),
        ("x = await self.g()", "x = self.g()"),
        ("async with lock:", "with lock:"),
        ("async for row in it:", "for row in it:"),
        ("def __aenter__(self):", "def __enter__(self):"),
        ("def __aexit__(self, *a):", "def __exit__(self, *a):"),
        ("def __aiter__(self):", "def __iter__(self):"),
        ("def __anext__(self):", "def __next__(self):"),
        ("await self.http.aclose()", "self.http.close()"),
        ("await r.aread()", "r.read()"),
        ("v = await anext(it)", "v = next(it)"),
        ("raise StopAsyncIteration", "raise StopIteration"),
        ("-> AsyncIterator[int]:", "-> Iterator[int]:"),
        ("@contextlib.asynccontextmanager", "@contextlib.contextmanager"),
        ("AbstractAsyncContextManager[None]", "AbstractContextManager[None]"),
        ("contextlib.AsyncExitStack()", "contextlib.ExitStack()"),
        ("store_lock_async(store, k)", "store_lock_sync(store, k)"),
        ("store: AsyncTokenStore", "store: TokenStore"),
        ("from .._async import x", "from .._sync import x"),
        ("AsyncInMemoryTokenStore()", "InMemoryTokenStore()"),
    ],
)
def test_convert_tokens(unasync: ModuleType, src: str, out: str) -> None:
    assert unasync.convert(src) == out


def test_convert_leaves_unrelated_words(unasync: ModuleType) -> None:
    for text in ("asyncio.sleep(1)", "awaiting = 1", "Asynchronous", "aclosed = True", "my_async_thing"):
        assert unasync.convert(text) == text


def test_generate_skips_hand_written_compat(unasync: ModuleType) -> None:
    files = unasync.generate()
    names = {p.relative_to(unasync.DST).as_posix() for p in files}
    assert "_compat.py" not in names
    assert {"client.py", "transport.py", "auth_runtime.py", "api/sobject.py"} <= names
    for text in files.values():
        assert text.startswith("# GENERATED by scripts/unasync.py")
        assert "async def" not in text
        assert "await " not in text


def test_regenerate_and_detect_stale(
    unasync: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    src = tmp_path / "_async"
    dst = tmp_path / "_sync"
    (src / "api").mkdir(parents=True)
    (src / "a.py").write_text("async def f():\n    await g()\n")
    (src / "api" / "b.py").write_text("class AsyncX: ...\n")
    (src / "_compat.py").write_text("ignored")
    dst.mkdir()
    (dst / "_compat.py").write_text("hand")
    (dst / "stale.py").write_text("old")
    monkeypatch.setattr(unasync, "SRC", src)
    monkeypatch.setattr(unasync, "DST", dst)
    monkeypatch.setattr(unasync, "ROOT", tmp_path)
    assert unasync.main(["--check"]) == 1
    assert unasync.main([]) == 0
    assert (dst / "a.py").read_text().endswith("def f():\n    g()\n")
    assert (dst / "api" / "b.py").read_text().endswith("class X: ...\n")
    assert (dst / "_compat.py").read_text() == "hand"
    assert not (dst / "stale.py").exists()
    assert unasync.main(["--check"]) == 0
