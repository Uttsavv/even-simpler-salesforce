"""Helpers shared by every ``esf generate`` target: the file header and the output file."""

from __future__ import annotations

import argparse
import shlex
from collections.abc import Callable, Mapping, Sequence
from datetime import datetime, timezone
from pathlib import Path
from typing import TextIO

__all__ = ["Handler", "file_header", "write_output"]

#: ``handler(args, env, out, err) -> exit code``, set on a target's subparser.
Handler = Callable[[argparse.Namespace, Mapping[str, str], TextIO, TextIO], int]


def _safe(text: str) -> str:
    """``text`` on one line: non-printable characters escaped, so it can't end a comment."""
    return "".join(ch if ch.isprintable() else repr(ch)[1:-1] for ch in text)


def file_header(
    what: str,
    *,
    command: Sequence[str],
    instance_url: str | None,
    org_id: str | None,
    api_version: str,
    now: datetime | None = None,
) -> str:
    """The comment block every generated file starts with.

    Args:
        what: One line saying what the file holds, e.g. ``"Typed sObject models"``.
        command: The ``esf`` arguments that generated the file (to regenerate it).
        instance_url: The org's instance URL.
        org_id: The org id.
        api_version: The API version the describe data came from.
        now: Generation time (defaults to the current UTC time).
    """
    when = (now or datetime.now(timezone.utc)).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        f"# {_safe(what)}, generated by esf. Don't edit by hand: regenerate instead.",
        f"#   org:         {_safe(instance_url or '-')} ({_safe(org_id or '-')})",
        f"#   api version: {_safe(api_version)}",
        f"#   generated:   {when}",
        f"#   command:     {_safe(shlex.join(['esf', *command]))}",
    ]
    return "\n".join(lines) + "\n"


def write_output(text: str, out_path: str | None, out: TextIO, err: TextIO) -> None:
    """Write generated ``text`` to ``out_path`` (UTF-8), or to stdout when it is ``None``."""
    if out_path is None:
        out.write(text)
        return
    path = Path(out_path).expanduser()
    try:
        path.write_text(text, encoding="utf-8")
    except OSError as exc:
        raise ValueError(f"cannot write {out_path}: {exc.strerror}") from None
    err.write(f"wrote {_safe(str(path))}\n")
