#!/usr/bin/env python3
"""Generate the sync client from the async source (§5.4).

    python scripts/unasync.py          # regenerate src/even_simpler_salesforce/_sync
    python scripts/unasync.py --check  # exit 1 if _sync is stale

``_async/_compat.py`` is not converted; ``_sync/_compat.py`` is hand-written.
Stdlib only.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "even_simpler_salesforce"
SRC = PKG / "_async"
DST = PKG / "_sync"
HAND_WRITTEN = {"_compat.py"}

HEADER = (
    "# GENERATED by scripts/unasync.py from _async/{name}. DO NOT EDIT.\n"
    "# Edit the async source and run `nox -s unasync` (or `python scripts/unasync.py`).\n"
)

# Ordered (pattern, replacement). Word-boundary regexes on the source text.
REPLACEMENTS: list[tuple[str, str]] = [
    (r"\basync def\b", "def"),
    (r"\basync with\b", "with"),
    (r"\basync for\b", "for"),
    (r"\bawait\s+", ""),
    (r"\b__aenter__\b", "__enter__"),
    (r"\b__aexit__\b", "__exit__"),
    (r"\b__aiter__\b", "__iter__"),
    (r"\b__anext__\b", "__next__"),
    (r"\baclose\b", "close"),
    (r"\baread\b", "read"),
    (r"\banext\b", "next"),
    (r"\bStopAsyncIteration\b", "StopIteration"),
    (r"\basynccontextmanager\b", "contextmanager"),
    (r"\bAbstractAsyncContextManager\b", "AbstractContextManager"),
    (r"\bAsyncExitStack\b", "ExitStack"),
    (r"\bstore_lock_async\b", "store_lock_sync"),
    (r"\bhttpx\.AsyncClient\b", "httpx.Client"),
    # Generic: AsyncFoo -> Foo (AsyncSalesforce, AsyncIterator, AsyncTokenStore, ...).
    (r"\bAsync([A-Z][A-Za-z0-9_]*)\b", r"\1"),
    (r"\b_async\b", "_sync"),
]
_COMPILED = [(re.compile(p), r) for p, r in REPLACEMENTS]


def convert(text: str) -> str:
    for pat, rep in _COMPILED:
        text = pat.sub(rep, text)
    return text


def generate() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for src in sorted(SRC.rglob("*.py")):
        rel = src.relative_to(SRC)
        if rel.as_posix() in HAND_WRITTEN:
            continue
        out[DST / rel] = HEADER.format(name=rel.as_posix()) + convert(src.read_text())
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if _sync is out of date")
    args = ap.parse_args(argv)
    files = generate()
    stale: list[Path] = []
    expected = set(files) | {DST / h for h in HAND_WRITTEN}
    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    extra = [p for p in DST.rglob("*.py") if p not in expected]
    for p in extra:
        stale.append(p)
        if not args.check:
            p.unlink()
    if args.check and stale:
        print("stale generated files:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    if not args.check:
        print(f"generated {len(files)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
