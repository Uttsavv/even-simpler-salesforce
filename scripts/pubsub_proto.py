#!/usr/bin/env python3
"""Regenerate the vendored Pub/Sub API stubs in ``src/even_simpler_salesforce/_pubsub`` (§5.5).

    uv run --with grpcio-tools==1.85.1 python scripts/pubsub_proto.py          # regenerate
    uv run --with grpcio-tools==1.85.1 python scripts/pubsub_proto.py --check  # fail on drift
    ... scripts/pubsub_proto.py --check --upstream   # also compare with GitHub at the pinned SHA

``--check`` fails when:

- the vendored ``pubsub_api.proto`` no longer matches the SHA-256 recorded below for the pinned
  upstream commit (someone edited it, or the pin moved without updating the hash);
- regenerating the stubs with the pinned ``grpcio-tools`` changes any committed file;
- the ``protobuf`` / ``grpcio`` minimums of the ``[pubsub]`` extra in ``pyproject.toml`` differ
  from the versions the stubs were generated for (older runtimes reject the stubs at import).

``--upstream`` downloads the proto from ``forcedotcom/pub-sub-api`` at the pinned commit and
compares it byte for byte (needs network; CI runs the offline check).

The proto is CC0-1.0 (public domain dedication), see ``_pubsub/NOTICE``.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PKG = SRC / "even_simpler_salesforce" / "_pubsub"
PROTO = PKG / "pubsub_api.proto"

UPSTREAM_REPO = "forcedotcom/pub-sub-api"
UPSTREAM_SHA = "03d49a9c21c10ca3b55fa7ab30db6ee69250378e"
PROTO_SHA256 = "0a651295ff3ff13551b3ae7cb6fe87cf91b749a8ae33b6079617dbc62f304eb5"
GRPCIO_TOOLS = "1.85.1"

GENERATED = ("pubsub_api_pb2.py", "pubsub_api_pb2.pyi", "pubsub_api_pb2_grpc.py")
HEADER = (
    "# GENERATED by scripts/pubsub_proto.py from pubsub_api.proto "
    f"({UPSTREAM_REPO}@{UPSTREAM_SHA[:12]}, grpcio-tools {GRPCIO_TOOLS}). DO NOT EDIT.\n"
)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate(out: Path) -> dict[str, str]:
    """Run protoc into ``out`` and return the generated files by name."""
    try:
        import grpc_tools  # noqa: F401
        from grpc_tools import protoc
    except ImportError:
        sys.exit(f"grpcio-tools is missing: run with `uv run --with grpcio-tools=={GRPCIO_TOOLS} ...`")
    from importlib.metadata import version

    if version("grpcio-tools") != GRPCIO_TOOLS:
        sys.exit(f"need grpcio-tools=={GRPCIO_TOOLS}, found {version('grpcio-tools')}")
    with tempfile.TemporaryDirectory() as tmp:
        # Compile from a copy under the package path, so the descriptor is registered as
        # ``even_simpler_salesforce/_pubsub/pubsub_api.proto`` and the grpc stub imports
        # ``even_simpler_salesforce._pubsub.pubsub_api_pb2`` (no top-level module names).
        rel = Path("even_simpler_salesforce") / "_pubsub" / "pubsub_api.proto"
        (Path(tmp) / rel).parent.mkdir(parents=True)
        shutil.copy(PROTO, Path(tmp) / rel)
        include = str(Path(protoc.__file__).parent / "_proto")
        rc = protoc.main(
            [
                "grpc_tools.protoc",
                f"-I{tmp}",
                f"-I{include}",
                f"--python_out={out}",
                f"--pyi_out={out}",
                f"--grpc_python_out={out}",
                str(rel),
            ]
        )
        if rc != 0:
            sys.exit(f"protoc failed ({rc})")
    gen = out / "even_simpler_salesforce" / "_pubsub"
    return {name: HEADER + (gen / name).read_text(encoding="utf-8") for name in GENERATED}


def runtime_versions(files: dict[str, str]) -> tuple[str, str]:
    """(protobuf, grpcio) versions the generated stubs require at runtime."""
    m = re.search(
        r"ValidateProtobufRuntimeVersion\(\s*_runtime_version\.Domain\.PUBLIC,\s*(\d+),\s*(\d+),\s*(\d+),",
        files["pubsub_api_pb2.py"],
    )
    g = re.search(r"GRPC_GENERATED_VERSION = '([\d.]+)'", files["pubsub_api_pb2_grpc.py"])
    if not m or not g:
        sys.exit("can't find the runtime versions in the generated stubs")
    return ".".join(m.groups()), g.group(1)


def extra_minimums() -> tuple[str | None, str | None]:
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    line = re.search(r"^pubsub = \[(.*)\]$", text, re.MULTILINE)
    if not line:
        return None, None
    pb = re.search(r'"protobuf>=([\d.]+)', line.group(1))
    gr = re.search(r'"grpcio>=([\d.]+)', line.group(1))
    return (pb.group(1) if pb else None), (gr.group(1) if gr else None)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the stubs or the pin drifted")
    ap.add_argument("--upstream", action="store_true", help="also compare the proto with GitHub")
    args = ap.parse_args(argv)
    problems: list[str] = []

    if sha256(PROTO.read_bytes()) != PROTO_SHA256:
        problems.append(f"{PROTO.relative_to(ROOT)} differs from {UPSTREAM_REPO}@{UPSTREAM_SHA} (sha256)")
    if args.upstream:
        url = f"https://raw.githubusercontent.com/{UPSTREAM_REPO}/{UPSTREAM_SHA}/pubsub_api.proto"
        with urllib.request.urlopen(url, timeout=30) as resp:
            if sha256(resp.read()) != PROTO_SHA256:
                problems.append(f"PROTO_SHA256 doesn't match {url}")

    with tempfile.TemporaryDirectory() as tmp:
        files = generate(Path(tmp))
    protobuf_min, grpcio_min = runtime_versions(files)
    have_pb, have_grpc = extra_minimums()
    if have_pb != protobuf_min:
        problems.append(f"[pubsub] needs protobuf>={protobuf_min} (stubs' runtime check), found {have_pb}")
    if have_grpc != grpcio_min:
        problems.append(f"[pubsub] needs grpcio>={grpcio_min} (stubs' runtime check), found {have_grpc}")

    stale = (
        [name for name, text in files.items() if (PKG / name).read_text(encoding="utf-8") != text]
        if (all((PKG / n).exists() for n in GENERATED))
        else list(GENERATED)
    )
    if args.check:
        problems.extend(f"stale generated stub: {PKG.relative_to(ROOT) / n}" for n in stale)
        if problems:
            print("pubsub_proto --check failed:", *problems, sep="\n  ")
            return 1
        print(f"pubsub stubs match {UPSTREAM_REPO}@{UPSTREAM_SHA[:12]} (protobuf>={protobuf_min})")
        return 0
    for name, text in files.items():
        (PKG / name).write_text(text, encoding="utf-8")
    for p in problems:
        print("warning:", p)
    print(f"generated {len(files)} files ({len(stale)} changed); stubs need protobuf>={protobuf_min}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
